/**
 * The lookup of the doc and decision blocks: a host's own definition of the same key (through
 * i18n.use()) wins; otherwise this dictionary answers in the platform language, falling back to
 * English, then to the key.
 * @param {string} key  a key with its prefix, `doc.` or `decision.`
 * @param {Record<string, any>} [vars]
 * @returns {string}
 */
export function td(key, vars) {
  const hosted = i18n.t(key, vars);
  if (hosted !== key) return hosted;
  const lang = i18n.lang();
  const table = /** @type {Record<string, string>} */ (
    (STRINGS[/** @type {'en'|'fi'|'es'} */ (lang)] || STRINGS.en));
  const text = table[key] || STRINGS.en[key] || key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, function (whole, name) {
    return vars[name] == null ? whole : String(vars[name]);
  });
}

/**
 * Whether the dictionary (or the host) has this key, so a caller can fall back to other words.
 * @param {string} key
 * @returns {boolean}
 */
export function hasWords(key) {
  return td(key) !== key;
}

