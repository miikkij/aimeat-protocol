/**
 * A word of the board family: the host's own `board.<key>` first, then this dictionary in the
 * kit's language, then English, then the key itself.
 * @param {string} key - without the `board.` prefix
 * @param {Record<string, any>} [vars]
 * @returns {string}
 */
export function tb(key, vars) {
  const hosted = i18n.t('board.' + key, vars);
  if (hosted !== 'board.' + key) return hosted;
  const lang = i18n.lang();
  const table = /** @type {Record<string, string>} */ (
    (STRINGS[/** @type {'en'|'fi'|'es'} */ (lang)] || STRINGS.en));
  const text = table[key] || STRINGS.en[key] || key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, function (whole, name) {
    return vars[name] == null ? whole : String(vars[name]);
  });
}
