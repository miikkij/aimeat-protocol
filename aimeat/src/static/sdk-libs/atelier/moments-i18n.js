/**
 * The moments' lookup: the host may override any key by defining `moments.<key>` through
 * i18n.use(); otherwise this dictionary answers in the platform language, falling back to English,
 * then to the empty string for a key no language has (a kind with no default lead has none).
 * @param {string} key
 * @param {Record<string, any>} [vars]
 * @returns {string}
 */
export function tmo(key, vars) {
  const hosted = kitWord('moments.' + key, vars);
  if (hosted !== 'moments.' + key) return hosted;
  const lang = i18n.lang();
  const table = /** @type {Record<string, string>} */ (
    (STRINGS[/** @type {'en'|'fi'|'es'} */ (lang)] || STRINGS.en));
  const en = /** @type {Record<string, string>} */ (STRINGS.en);
  const text = table[key] || en[key] || '';
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, function (whole, name) {
    return vars[name] == null ? whole : String(vars[name]);
  });
}
