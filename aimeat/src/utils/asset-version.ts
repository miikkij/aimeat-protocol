/**
 * @file asset-version.ts
 * @author Jouni Miikki
 * SPDX-License-Identifier: MIT
 * @description The `?v=` tag of one first-party module or stylesheet, taken from the file's own
 *   bytes, so the address changes when the file changes and at no other time.
 *
 *   Until 2026-11-06 the shell stamped every importmap module and every stylesheet link with the
 *   build stamp (routes/portal-spa.ts BUILD_ID). Each deploy therefore gave all ~790 files a new
 *   address at once, unchanged files included, and Google found a new set of URLs after every
 *   release: Search Console of 2026-11-05 listed 4 515 addresses as "Crawled, currently not
 *   indexed", and every example was a .js file with a `?v=` tag (TARGET-090). A browser gained
 *   nothing from the churn either: an unchanged file is the same bytes under a new name, fetched
 *   again.
 *
 *   A content tag keeps the one thing the build stamp was for. A changed file gets a new address,
 *   so a browser that holds the old module in its module map loads the new one; an unchanged file
 *   keeps its address across deploys, so neither a browser nor a crawler fetches it again.
 *
 *   THE CACHE. A file is read and hashed once and the tag is kept with the file's size and mtime.
 *   In a frozen tree (a stamped build from a clean commit, whose public/ is copied at build time)
 *   the tag is kept for the life of the process. Anywhere else (a source checkout run through tsx,
 *   a dirty build) the size and mtime are compared on every call, so an edited file gets its new
 *   tag on the next page load, as the per-process stamp did before.
 *
 *   A path that is not a file under the root answers null, and the caller keeps the build stamp
 *   for it: a route that serves generated bytes has no file to hash.
 * @structure
 *   - assetTag(bytes)                 — the tag of a byte string
 *   - createAssetVersioner(root, opts) — a cached path → `?v=<tag>` lookup over one directory
 *   - publicAssetVersioner(frozen)     — the one over the served public/ tree
 * @usage
 *   const versionOf = publicAssetVersioner(frozen);
 *   versionOf('/components/Mark.js'); // '?v=3f1c0a9b2e' or null
 * @version-history
 *   v1.0.0 — 2026-11-06 — Initial (TARGET-090 Y2).
 */
import { createHash } from 'node:crypto';
import { readFileSync, statSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveAssetDir } from '../server-bootstrap/asset-dirs.js';
import { logger } from './logger.js';

/** Ten hex characters of SHA-256: 40 bits, so two versions of one file do not collide in practice. */
export function assetTag(bytes: Buffer | string): string {
  return createHash('sha256').update(bytes).digest('hex').slice(0, 10);
}

interface Entry { size: number; mtimeMs: number; query: string }

/** A lookup from a URL path under `root` to its `?v=<tag>`, or null when no such file exists. */
export type AssetVersioner = (urlPath: string) => string | null;

/**
 * A cached lookup over one directory.
 *
 * The path comes from the node's own HTML, never from a request, but it is still held inside the
 * root: a `..` segment or a path that resolves outside answers null rather than hashing whatever it
 * names.
 */
export function createAssetVersioner(root: string | undefined, opts: { frozen: boolean }): AssetVersioner {
  const cache = new Map<string, Entry | null>();
  if (!root) return () => null;
  const base = resolve(root);

  return (urlPath: string): string | null => {
    if (!urlPath.startsWith('/') || urlPath.includes('..') || urlPath.includes('\0')) return null;
    const known = cache.get(urlPath);
    if (known !== undefined && opts.frozen) return known?.query ?? null;

    const file = resolve(join(base, urlPath));
    if (!file.startsWith(base + sep)) return null;

    let size: number;
    let mtimeMs: number;
    let bytes: Buffer;
    try {
      const st = statSync(file);
      if (!st.isFile()) { cache.set(urlPath, null); return null; }
      size = st.size;
      mtimeMs = st.mtimeMs;
      if (known && known.size === size && known.mtimeMs === mtimeMs) return known.query;
      bytes = readFileSync(file);
    } catch (err) {
      // No such file is an answer: the caller keeps the build stamp for that path. Anything else
      // (a permission, an I/O error) is a fault, logged, and the build stamp is kept the same way,
      // so the page still loads with an address that busts the cache.
      const code = (err as NodeJS.ErrnoException).code;
      if (code !== 'ENOENT' && code !== 'ENOTDIR') {
        logger.warn('asset-version: could not read a public file to tag it; its build stamp is used', { path: urlPath, error: String(err) });
      }
      cache.delete(urlPath);
      return null;
    }
    const entry = { size, mtimeMs, query: `?v=${assetTag(bytes)}` };
    cache.set(urlPath, entry);
    return entry.query;
  };
}

let shared: AssetVersioner | undefined;

/**
 * The lookup over the public/ tree express.static serves (server-bootstrap/static-files.ts reads the
 * same resolveAssetDir answer), so the tag is taken from the bytes a browser receives.
 */
export function publicAssetVersioner(frozen: boolean): AssetVersioner {
  shared ??= createAssetVersioner(
    resolveAssetDir('public', dirname(fileURLToPath(import.meta.url)), process.cwd()),
    { frozen },
  );
  return shared;
}
