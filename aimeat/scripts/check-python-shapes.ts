/**
 * @file check-python-shapes.ts
 * @author Jouni Miikki
 * SPDX-License-Identifier: MIT
 * @description Gate: the offer and signal shapes the Python package builds agree with the node's
 *   zod schemas, field by field, or the difference is listed with its reason in
 *   security/python-shape-parity.json. Also holds the JSON Schema fixture the package's pytest
 *   validates against (python/aimeat-crewai/tests/fixtures/node-offer-schema.json) to the zod
 *   schemas it was generated from. The comparison and why it reads Python source:
 *   scripts/inventory/python-shapes.ts.
 *
 *   FAILS ON: a difference the allowlist does not name; an allowlist entry whose difference is gone
 *   (delete it, and lower SHAPE_CEILING); an entry without a reason; more entries than
 *   SHAPE_CEILING; a stale or missing fixture (`pnpm python:schema` rewrites it); a Python builder
 *   the extraction cannot read.
 *
 *   The paths come from the environment when set (AIMEAT_PARITY_PYTHON_SRC, AIMEAT_PARITY_FIXTURE,
 *   AIMEAT_PARITY_SHAPE_ALLOWLIST), so the gate self-test runs this script on a planted copy.
 * @usage
 *   pnpm check:python-shapes            # the gate
 *   pnpm python:schema                  # rewrite the fixture after a node schema change
 * @version-history
 *   v1.0.0 — 2026-10-18 — Initial (wish wish-vertailutarkistus-python-paketin-ja-liittimen-kahdennuksille).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { nodeShapes, readPythonShapes, shapeFindings, SHAPE_CEILING, SHAPE_ALLOWLIST } from './inventory/python-shapes.js';

const AIMEAT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(AIMEAT, '..');
const PY_SRC = process.env.AIMEAT_PARITY_PYTHON_SRC ?? join(REPO, 'python', 'aimeat-crewai', 'src', 'aimeat_crewai');
const FIXTURE = process.env.AIMEAT_PARITY_FIXTURE ?? join(REPO, 'python', 'aimeat-crewai', 'tests', 'fixtures', 'node-offer-schema.json');
const ALLOWLIST = process.env.AIMEAT_PARITY_SHAPE_ALLOWLIST ?? join(AIMEAT, SHAPE_ALLOWLIST);

/** The fixture's text: the node's schemas with a header saying where they come from. LF, two spaces. */
function fixtureText(): string {
    const doc = {
        $comment: 'GENERATED by `pnpm python:schema` (aimeat/scripts/check-python-shapes.ts --write) from aimeat/src/models/offer-schemas.ts '
            + 'and workflow-signals.ts. Do not edit: `pnpm check:python-shapes` fails when this differs from the zod schemas. '
            + 'Read by tests/test_node_schema_parity.py.',
        ...nodeShapes(),
    };
    return JSON.stringify(doc, null, 2) + '\n';
}

function main(): void {
    if (process.argv.includes('--write')) {
        writeFileSync(FIXTURE, fixtureText(), 'utf8');
        console.log(`✓ wrote ${FIXTURE}`);
        return;
    }
    const problems: string[] = [];

    if (!existsSync(FIXTURE)) problems.push(`the fixture ${FIXTURE} is missing: run \`pnpm python:schema\``);
    else if (readFileSync(FIXTURE, 'utf8').replace(/\r\n/g, '\n') !== fixtureText()) {
        problems.push('the fixture python/aimeat-crewai/tests/fixtures/node-offer-schema.json no longer matches the node\'s zod schemas: '
            + 'run `pnpm python:schema` and commit it with the schema change, so the package\'s pytest validates against the new shape');
    }

    const py = readPythonShapes(PY_SRC);
    for (const u of py.unreadable) problems.push(`cannot read ${u}: the extraction in scripts/inventory/python-shapes.ts has to follow the Python change`);

    const findings = shapeFindings(nodeShapes(), py);
    const allow = (JSON.parse(readFileSync(ALLOWLIST, 'utf8')) as { exempt?: Record<string, string> }).exempt ?? {};
    const unlisted = findings.filter(f => !(f in allow));
    const gone = Object.keys(allow).filter(k => !findings.includes(k));
    const reasonless = Object.entries(allow).filter(([, v]) => typeof v !== 'string' || v.trim().length < 20).map(([k]) => k);
    const count = Object.keys(allow).length;

    for (const f of unlisted) problems.push(`difference not in ${SHAPE_ALLOWLIST}: ${f}`);
    for (const f of gone) problems.push(`${SHAPE_ALLOWLIST} lists ${f}, which no longer differs: delete the entry and lower SHAPE_CEILING`);
    for (const f of reasonless) problems.push(`${SHAPE_ALLOWLIST}: ${f} has no reason`);
    if (count > SHAPE_CEILING) problems.push(`${SHAPE_ALLOWLIST} holds ${count} entries and the ceiling is ${SHAPE_CEILING}: the list only shrinks, and a new entry is the developer's decision`);

    if (problems.length > 0) {
        console.error(`✗ check:python-shapes: ${problems.length} problem(s)`);
        for (const p of problems) console.error(`  - ${p}`);
        console.error('  A node field the Python builder does not name: add it to build_offer (python/aimeat-crewai/src/aimeat_crewai/offers.py)'
            + ' or Sig (workflow_spec.py), or list the difference with the reason it is deliberate. The node schema wins on any mismatch.');
        process.exit(1);
    }
    console.log(`✓ check:python-shapes: offer and signal shapes agree with the Python builders (${findings.length} listed difference(s), ceiling ${SHAPE_CEILING}); fixture fresh`);
}

main();
