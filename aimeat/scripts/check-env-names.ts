/**
 * @file scripts/check-env-names.ts
 * @author Jouni Miikki
 * SPDX-License-Identifier: MIT
 * @description Keeps src/config/known-env-names.ts equal to the AIMEAT_* names the repository's
 *   tracked files mention, so the node's start can name a variable nothing reads.
 *
 *   WHY. A scratch node started with `AIMEAT_DB=sqlite` and `AIMEAT_DB_PATH=…` in its env file wrote
 *   into the developer's dev database: those are flag names, no code reads them as variables, and
 *   the node filled AIMEAT_STORAGE and DATABASE_URL from aimeat/.env instead (docs/pitfalls.md §23
 *   until 2026-11-21). The node now warns at start about an AIMEAT_* variable that appears nowhere
 *   in this repository (src/config/unknown-env.ts), and that needs the list of names that do.
 *   Tracked files only, so the list is the same on every machine.
 * @usage
 *   cd aimeat && pnpm check:env-names          # refuses when the list is out of date
 *   cd aimeat && pnpm check:env-names --write  # writes it
 * @version-history
 *   v1.0.0 — 2026-11-21 — Initial.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const AIMEAT = process.cwd();
const REPO = resolve(AIMEAT, '..');
const TARGET = join(AIMEAT, 'src', 'config', 'known-env-names.ts');
const TEXT = /\.(?:ts|js|mjs|cjs|md|ya?ml|json|sh|py|toml|txt|html|example)$|(?:^|\/)\.env[^/]*$/;
const SKIP = /^(?:aimeat\/locales\/|aimeat\/public\/lib\/|aimeat\/src\/config\/known-env-names\.ts$)|pnpm-lock\.yaml$/;

/** Every AIMEAT_* name the tracked text files mention, sorted. */
export function repoEnvNames(repo: string = REPO): string[] {
    const files = execFileSync('git', ['ls-files'], { cwd: repo, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
        .split('\n').filter(f => f && TEXT.test(f) && !SKIP.test(f));
    const names = new Set<string>();
    for (const f of files) {
        let text: string;
        try { text = readFileSync(join(repo, f), 'utf8'); } catch { continue; }
        for (const m of text.matchAll(/\bAIMEAT_[A-Z0-9_]*[A-Z0-9]\b/g)) names.add(m[0]);
    }
    return [...names].sort();
}

/** The generated module's text. Eight names a line keeps it far under the file length limit. */
export function render(names: string[]): string {
    const rows: string[] = [];
    for (let i = 0; i < names.length; i += 8) rows.push(`  ${names.slice(i, i + 8).join(' ')}`);
    return `/**
 * @file src/config/known-env-names.ts
 * @author Jouni Miikki
 * SPDX-License-Identifier: MIT
 * @description GENERATED by \`pnpm check:env-names --write\`; do not edit by hand. Every AIMEAT_*
 *   name the repository's tracked files mention (code, scripts, tests, docs, examples), read by the
 *   start-time warning about a variable nothing reads (src/config/unknown-env.ts).
 * @version-history
 *   v1.0.0 — 2026-11-21 — Initial.
 */
export const KNOWN_ENV_NAMES: ReadonlySet<string> = new Set(\`
${rows.join('\n')}
\`.split(/\\s+/).filter(Boolean));
`;
}

function main(): void {
    const next = render(repoEnvNames());
    let current = '';
    try { current = readFileSync(TARGET, 'utf8'); } catch { /* not written yet */ }
    if (process.argv.includes('--write')) {
        writeFileSync(TARGET, next);
        console.log(`  wrote ${TARGET.slice(AIMEAT.length + 1)}`);
        return;
    }
    const strip = (t: string) => t.replace(/\r\n/g, '\n');
    if (strip(current) === strip(next)) {
        console.log('  ✓ src/config/known-env-names.ts lists every AIMEAT_* name the repository mentions');
        return;
    }
    const listed = /new Set\(`([\s\S]*?)`/.exec(strip(current))?.[1] ?? '';
    const have = new Set(listed.split(/\s+/).filter(w => /^AIMEAT_/.test(w)));
    const want = repoEnvNames();
    const added = want.filter(n => !have.has(n));
    const gone = [...have].filter(n => !want.includes(n));
    console.error(`\n✖ src/config/known-env-names.ts is out of date${added.length ? `; new: ${added.slice(0, 8).join(', ')}` : ''}${gone.length ? `; gone: ${gone.slice(0, 8).join(', ')}` : ''}.`);
    console.error('  The node warns at start about an AIMEAT_* variable this list does not name. Run:');
    console.error('    cd aimeat && pnpm check:env-names --write\n');
    process.exit(1);
}

const invokedDirectly = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) main();
